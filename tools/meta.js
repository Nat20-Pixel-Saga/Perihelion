import fs from 'node:fs';
import path from 'node:path';
import { speaker } from '../engine/world.js';
import { ROOT, releaseDir, ensureDir, season, clock, rel, availableTracks } from './lib.js';
import { trailerPlan } from './video.js';

const DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const pad = n => String(n).padStart(2, '0');

// Wall-clock time in a named zone -> ISO string with that zone's offset on that date.
function zoned(dateStr, timeStr, tz) {
  const guess = new Date(dateStr + 'T' + timeStr + ':00Z');
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }).formatToParts(guess).map(p => [p.type, p.value]));
  const shown = Date.UTC(+parts.year, +parts.month - 1, +parts.day, +parts.hour, +parts.minute);
  const off = Math.round((shown - guess.getTime()) / 60000), sign = off >= 0 ? '+' : '-';
  return dateStr + 'T' + timeStr + ':00' + sign + pad(Math.floor(Math.abs(off) / 60)) + ':' + pad(Math.abs(off) % 60);
}
const addDays = (dateStr, n) => { const d = new Date(dateStr + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); };
const dow = dateStr => DAYS[new Date(dateStr + 'T12:00:00Z').getUTCDay()];
const nice = dateStr => new Date(dateStr + 'T12:00:00Z').toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long', timeZone: 'UTC' });

// Air dates for n episodes on the configured weekdays.
export function calendar(n) {
  const sc = season().schedule, out = [];
  let d = sc.firstEpisode;
  while (out.length < n) { if (sc.days.includes(dow(d))) out.push({ date: d, episodeAt: zoned(d, sc.time, sc.timezone), trailerAt: zoned(addDays(d, -sc.trailerDaysBefore), sc.time, sc.timezone) }); d = addDays(d, 1); }
  return out;
}

export function chapters(ep) {
  return ep.scenes.map((s, i) => ({ t: i === 0 ? 0 : s.t, title: s.title }));
}

export function writeMeta(ep, all) {
  const se = season(), m = ep.meta, n = m.number, cal = calendar(Math.max(all.length, n)), slot = cal[n - 1];
  const next = all.find(x => x.meta.number === n + 1), dir = releaseDir(m.id);
  const usedFile = path.join(ROOT, 'dist', m.id, 'music-used.json');
  const used = fs.existsSync(usedFile) ? JSON.parse(fs.readFileSync(usedFile, 'utf8')) : Object.values(availableTracks()).map(t => ({ title: t.title, author: t.author, license: t.license, page: t.page }));
  const music = used.length
    ? 'Music (all CC0, public domain):\n' + used.map(t => '· "' + t.title + '" by ' + t.author + ' · ' + t.page).join('\n') + '\nSound design: generated by the Perihelion pipeline.'
    : 'Music and sound: original score generated by the Perihelion pipeline.';
  const title = m.title + ' | ' + se.series + ' S' + se.season + ' E' + n;
  const description = [
    m.logline, '', se.about, '',
    'Chapters', ...chapters(ep).map(c => clock(c.t) + ' ' + c.title), '',
    'Episode ' + n + ' of ' + all.length + ' · Season ' + se.season + (next ? '\nNext: "' + next.meta.title + '" on ' + nice(cal[n].date) : '\nSeason finale.'),
    se.playlistUrl ? 'Full season: ' + se.playlistUrl : null, '',
    music, 'Made with open tools: ' + se.repo, '',
    se.hashtags.join(' ')
  ].filter(x => x !== null).join('\n');
  const plan = m.trailer ? trailerPlan(ep) : null;
  const shortTitle = m.trailer ? (m.trailer.hook.replace(/\.$/, '') + ' | ' + se.series + ' E' + n + ' #shorts').slice(0, 100) : '';
  const shortDescription = m.trailer ? [m.logline, '', 'Trailer for episode ' + n + ', "' + m.title + '". Full episode ' + nice(slot.date) + ' on this channel.', '', '#shorts ' + se.hashtags.join(' ')].join('\n') : '';
  if (title.length > 100) throw new Error(m.id + ': title over 100 characters');
  fs.writeFileSync(path.join(dir, 'title.txt'), title + '\n');
  fs.writeFileSync(path.join(dir, 'description.txt'), description + '\n');
  fs.writeFileSync(path.join(dir, 'tags.txt'), se.tags.join(', ') + '\n');
  fs.writeFileSync(path.join(dir, 'short-title.txt'), shortTitle + '\n');
  fs.writeFileSync(path.join(dir, 'short-description.txt'), shortDescription + '\n');
  const trailerTitle = m.trailer ? ('Trailer: ' + m.title + ' | ' + se.series + ' S' + se.season + ' E' + n).slice(0, 100) : '';
  const trailerDescription = m.trailer ? [m.trailer.hook, '', m.logline, '', 'Episode ' + n + ', "' + m.title + '", airs ' + nice(slot.date) + ' on this channel.', se.playlistUrl ? 'Full season: ' + se.playlistUrl : null, '', se.about, '', se.hashtags.join(' ')].filter(x => x !== null).join('\n') : '';
  fs.writeFileSync(path.join(dir, 'trailer-title.txt'), trailerTitle + '\n');
  fs.writeFileSync(path.join(dir, 'trailer-description.txt'), trailerDescription + '\n');
  fs.writeFileSync(path.join(dir, 'script.md'), script(ep));
  const json = {
    id: m.id, number: n, title, logline: m.logline, runtimeSeconds: ep.duration, publishAt: slot.episodeAt,
    chapters: chapters(ep).map(c => ({ at: clock(c.t), title: c.title })), tags: se.tags,
    files: { video: 'dist/' + m.id + '/' + m.id + '.mp4', thumbnail: 'release/' + m.id + '/thumbnail.png', description: 'release/' + m.id + '/description.txt' },
    trailer: plan ? { runtimeSeconds: +plan.total.toFixed(1), publishAt: slot.trailerAt, wide: { title: trailerTitle, video: 'dist/' + m.id + '/' + m.id + '-trailer.mp4', thumbnail: 'release/' + m.id + '/thumbnail.png' }, short: { title: shortTitle, video: 'dist/' + m.id + '/' + m.id + '-short.mp4' } } : null
  };
  fs.writeFileSync(path.join(dir, 'meta.json'), JSON.stringify(json, null, 2) + '\n');
  console.log(m.id + ' metadata · ' + rel(dir));
  return json;
}

// Upload text for the season trailer (both formats). `plans` are the wide and short plans.
export function writeSeasonTrailerMeta(spec, all, plans) {
  const se = season(), sc = se.schedule, dir = ensureDir(path.join(ROOT, 'release', spec.id + '-trailer'));
  const first = nice(sc.firstEpisode), at = zoned(addDays(sc.firstEpisode, -(sc.seasonTrailerDaysBefore || 7)), sc.time, sc.timezone);
  const days = sc.days.join(', ');
  const title = (se.series.toUpperCase() + ' | Season ' + se.season + ' trailer');
  const description = [spec.hook, '', 'A survey ship follows a chain of beacons left by a lost expedition. Each beacon pulses at an interval equal to the number of people who were still aboard when it was set, and the number keeps falling.', '', se.about, '', 'Season ' + se.season + ': ' + all.length + ' episodes, starting ' + first + '. New episodes ' + days + ' at ' + sc.time + ' (' + sc.timezone.split('/')[1] + ' time).', se.playlistUrl ? 'Full season: ' + se.playlistUrl : null, '', 'Music and sound: original score generated by the Perihelion pipeline.', '', se.hashtags.join(' ')].filter(x => x !== null).join('\n');
  const shortTitle = (spec.hook.replace(/\.$/, '') + ' | ' + se.series + ' season ' + se.season + ' #shorts').slice(0, 100);
  const shortDescription = ['A science-fiction serial told entirely through a ship\'s console. Season ' + se.season + ' starts ' + first + ' on this channel.', '', '#shorts ' + se.hashtags.join(' ')].join('\n');
  fs.writeFileSync(path.join(dir, 'title.txt'), title + '\n'); fs.writeFileSync(path.join(dir, 'description.txt'), description + '\n');
  fs.writeFileSync(path.join(dir, 'short-title.txt'), shortTitle + '\n'); fs.writeFileSync(path.join(dir, 'short-description.txt'), shortDescription + '\n');
  fs.writeFileSync(path.join(dir, 'meta.json'), JSON.stringify({ id: spec.id + '-trailer', publishAt: at, tags: se.tags,
    wide: { title, runtimeSeconds: +plans.wide.total.toFixed(1), video: 'dist/' + spec.id + '/' + spec.id + '-trailer.mp4', thumbnail: 'release/' + spec.id + '-trailer/thumbnail.png' },
    short: { title: shortTitle, runtimeSeconds: +plans.short.total.toFixed(1), video: 'dist/' + spec.id + '/' + spec.id + '-short.mp4' } }, null, 2) + '\n');
  console.log(spec.id + ' trailer metadata · ' + rel(dir));
  return at;
}

export function writeSchedule(all) {
  const se = season(), cal = calendar(all.length), sc = se.schedule;
  const rows = all.map((ep, i) => '| ' + ep.meta.number + ' | ' + ep.meta.title + ' | ' + clock(ep.duration) + ' | ' + nice(cal[i].date) + ' | ' + cal[i].trailerAt + ' | ' + cal[i].episodeAt + ' |');
  const md = ['# Release schedule · season ' + se.season, '',
    'Episodes air ' + sc.days.join(', ') + ' at ' + sc.time + ' ' + sc.timezone + '. Each trailer goes out ' + sc.trailerDaysBefore + ' day before its episode.',
    'Change `schedule.firstEpisode` in `season.json` and run `npm run meta` to move every date.', '',
    'The season trailer (16:9 and 9:16) goes out ' + (sc.seasonTrailerDaysBefore || 7) + ' days before episode 1: ' + zoned(addDays(sc.firstEpisode, -(sc.seasonTrailerDaysBefore || 7)), sc.time, sc.timezone) + '. Each episode trailer exists in both formats and both publish at the trailer time below.', '',
    '| # | Title | Runtime | Airs | Trailer publishes | Episode publishes |', '| --- | --- | --- | --- | --- | --- |', ...rows, ''].join('\n');
  fs.writeFileSync(path.join(ROOT, 'release', 'schedule.md'), md);
  fs.writeFileSync(path.join(ROOT, 'release', 'schedule.json'), JSON.stringify(all.map((ep, i) => ({ id: ep.meta.id, title: ep.meta.title, trailerAt: cal[i].trailerAt, episodeAt: cal[i].episodeAt })), null, 2) + '\n');
  console.log('schedule · release/schedule.md');
}

// The episode as a readable script.
export function script(ep) {
  const out = ['# ' + ep.meta.title, '', 'Perihelion · episode ' + ep.meta.number + ' · ' + clock(ep.duration), '', ep.meta.logline, ''];
  const prev = {}; let inLog = false, n = 0;
  const closeLog = () => { if (inLog) { out.push(''); inLog = false; } };
  for (const e of ep.events) {
    if (e.type === 'scene') { closeLog(); out.push('## Scene ' + ++n + ' · ' + e.title + ' (' + clock(e.t) + ')', ''); }
    else if (e.type === 'clock') { if (e.t > 0) { closeLog(); out.push('`day ' + e.day + ' · ' + e.time + '`', ''); } }
    else if (e.type === 'note') { closeLog(); out.push('*' + e.text + '*', ''); }
    else if (e.type === 'logOpen') { closeLog(); out.push('**' + (e.tone === 'teal' ? 'LOG, WRITTEN BY NO ONE' : "CAPTAIN'S LOG") + ' · ' + e.stamp + '**', ''); out.push('> '); inLog = true; }
    else if (e.type === 'logType') { if (!inLog) { out.push('> '); inLog = true; } out[out.length - 1] += (e.tone === 'teal' ? '[teal] ' : '') + e.text; }
    else if (e.type === 'logErase') { const line = out[out.length - 1]; out[out.length - 1] = line.slice(0, line.length - e.erased.length) + '~~' + e.erased.trim() + '~~ '; }
    else if (e.type === 'say') { closeLog(); out.push('**' + speaker(e.who).name + (e.priv ? ' (private)' : '') + ':** ' + e.text, ''); }
    else if (e.type === 'readout') { closeLog(); out.push('**ON SCREEN · ' + e.head + '**', '', '> ' + e.text, ''); }
    else if (e.type === 'meter') { if (prev[e.name] !== undefined && prev[e.name] !== e.to) { closeLog(); out.push('*Meter: ' + e.name + ' ' + prev[e.name] + '% to ' + e.to + '%.*', ''); } prev[e.name] = e.to; }
    else if (e.type === 'tx') { closeLog(); out.push('*Signal strip: ' + e.label + '.*', ''); }
    else if (e.type === 'end') { closeLog(); out.push('*End card.' + (e.next ? ' Next: ' + e.next + '.' : '') + '*', ''); }
  }
  return out.join('\n');
}
